#!/bin/zsh
# Builds a release binary and wraps it into build/BetterActivityMonitor.app (ad-hoc signed).
set -euo pipefail

cd "$(dirname "$0")/.."
CONFIG="${1:-release}"
APP="build/BetterActivityMonitor.app"

swift build -c "$CONFIG"
BIN="$(swift build -c "$CONFIG" --show-bin-path)/BetterActivityMonitor"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
# SwiftPM stamps the deployment target as the SDK version (sdk 14.0), which makes AppKit use the
# legacy window chrome. Re-stamp with the real SDK so the app gets the current system design.
SDK_VERSION="$(xcrun --show-sdk-version)"
vtool -set-build-version macos 14.0 "$SDK_VERSION" -replace -output "$APP/Contents/MacOS/BetterActivityMonitor" "$BIN"
cp Resources/Info.plist "$APP/Contents/Info.plist"
# The plist takes its version from the Xcode project (MARKETING_VERSION); VERSION and BUILD_NUMBER override it.
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString ${VERSION:-$(scripts/version.sh)}" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion ${BUILD_NUMBER:-$(scripts/version.sh build)}" "$APP/Contents/Info.plist"

# App icon (generated by scripts/make-icon.sh). macOS 26+ shows a plain .icns shrunk onto a grey
# tile, so the Icon Composer document is compiled into Assets.car (CFBundleIconName); the .icns is
# the fallback for older systems (CFBundleIconFile).
xcrun actool Resources/AppIcon.icon --compile "$APP/Contents/Resources" --app-icon AppIcon \
  --platform macosx --target-device mac --minimum-deployment-target 14.0 \
  --output-partial-info-plist build/actool-partial.plist >/dev/null
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"

codesign --force --sign - "$APP"
# Make Finder/Dock pick up icon changes instead of a cached icon.
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP"
echo "Built $APP"
